#!/usr/bin/env python3
"""Thirty-sixth patch layer: a better Weather place. Settings > Options gets "Weather country" (Auto, then about 60 countries) and "Weather city" now steps
through the cities of that country (exact coordinates from tools/cities.json, made by tools/gen_cities.py). Auto still finds the place from the internet connection."""
import json, os
APP = os.path.expanduser('~/Developer/webos-launcher-tvos/app')
ROOT = os.path.expanduser('~/Developer/webos-launcher-tvos')
def P(p): return os.path.join(APP, p)
def sub(p, pairs):
    s = open(P(p)).read()
    for a, b in pairs:
        assert a in s, (p, a[:80])
        s = s.replace(a, b)
    open(P(p), 'w').write(s)

data = json.load(open(f'{ROOT}/tools/cities.json'))
seen = set()
for c in data:
    for city in c['cities']:
        if city['name'] in seen: city['name'] = f"{city['name']} ({c['code']})"
        seen.add(city['name'])
open(P('src/config/cities.ts'), 'w').write(
"// Places for the Weather options: a country, then one of its larger cities (the TV has no keyboard, so the options step through lists).\n"
"// Auto = found from the internet connection. Generated by tools/gen_cities.py.\n"
"export interface City { name: string; lat: number; lon: number; }\nexport interface Country { code: string; name: string; cities: City[]; }\n\n"
"export const COUNTRIES: Country[] = " + json.dumps(data, ensure_ascii=False, indent='\t') + ";\n\n"
"export const CITIES: City[] = COUNTRIES.reduce((all, c) => all.concat(c.cities), [] as City[]);\n")

sub('src/lib/storage.ts', [
 ("	/** weather place:", "	/** weather country (a code from config/cities.ts), '' = not chosen */\n	weatherCountry: string;\n	/** weather place:"),
 ("	weatherCity: '',\n", "	weatherCountry: '',\n	weatherCity: '',\n"),
 ("			weatherCity: typeof parsed.weatherCity", "			weatherCountry: typeof parsed.weatherCountry === 'string' ? parsed.weatherCountry : '',\n			weatherCity: typeof parsed.weatherCity"),
])
sub('src/lib/i18n.ts', [
 ("const TABLE: Record<string, string[]> = {", "const TABLE: Record<string, string[]> = {\n\t\"Weather country\": [\"Wetter-Land\", \"País del tiempo\", \"Pays météo\", \"Paese meteo\", \"País do tempo\", \"Weerland\", \"Hava durumu ülkesi\", \"मौसम देश\"],"),
])
sub('src/app.tsx', [
 ("import {CITIES} from './config/cities';", "import {CITIES, COUNTRIES} from './config/cities';"),
 ("city: 'weather-city',", "city: 'weather-city', country: 'weather-country',"),
 ("], [config.dockHide,", "], [config.weatherCountry, config.dockHide,"),
 ("		{\n			id: OPTION.city,", "		{\n			id: OPTION.country,\n			label: 'Weather country',\n			description: 'Pick your country, then the city below. Auto finds your area from your internet connection (ipwho.is), which can be a few towns off.',\n			value: config.weatherCountry !== '',\n			valueText: (COUNTRIES.filter((c) => c.code === config.weatherCountry)[0] || {name: 'Auto'}).name\n		},\n		{\n			id: OPTION.city,"),
 ("			const names = [''].concat(CITIES.map((c) => c.name));\n			updateConfig({...config, weatherCity: names[(names.indexOf(config.weatherCity) + 1) % names.length]});",
  "			const country = COUNTRIES.filter((c) => c.code === config.weatherCountry)[0];\n			const names = [''].concat((country ? country.cities : CITIES).map((c) => c.name));\n			const next = names[(names.indexOf(config.weatherCity) + 1) % names.length];\n			const owner = COUNTRIES.filter((c) => c.cities.some((x) => x.name === next))[0];\n			updateConfig({...config, weatherCity: next, weatherCountry: country ? country.code : owner ? owner.code : ''});"),
 ("		} else if (optionId === OPTION.dockHide) {", "		} else if (optionId === OPTION.country) {\n			const codes = [''].concat(COUNTRIES.map((c) => c.code));\n			const next = codes[(codes.indexOf(config.weatherCountry) + 1) % codes.length];\n			const first = COUNTRIES.filter((c) => c.code === next)[0];\n			updateConfig({...config, weatherCountry: next, weatherCity: first ? first.cities[0].name : ''});\n		} else if (optionId === OPTION.dockHide) {"),
])
